import Foundation
import AppKit
func check(_ condition: @autoclosure () -> Bool, _ label: String) { if !condition() { fatalError(label) } }
let input = "[00:02.50]Second line\n[00:00.00]First line\n[00:04.00][00:08.00]Repeated line\n[00:06.00]\n[artist:Example]"
let lines = LyricsDocument.parse(input)
check(lines.count == 5, "multiple timestamps and blank cues")
let doc = LyricsDocument(lines: lines, phase: "synced")
check(doc.active(at: -1) == nil, "before first cue")
check(doc.active(at: 0) == 0, "exact cue boundary")
check(doc.active(at: 5) == 2, "middle playback")
check(doc.active(at: 2.5) == 1, "backward seek")
check(doc.active(at: 99) == 4, "after final cue")
check(doc.active(at: .nan) == nil, "nonfinite time")
check(LyricsDocument.parse("[offset:500]\n[00:02.000]Line").first?.time == 1.5, "LRC offset")
check(LyricsDocument.parse("[00:70]Bad\nNo timestamp").isEmpty, "bad timestamp")
check(LyricsDocument.parse(String(repeating: "x", count: 300000)).isEmpty, "oversized input")
let instrumental = Data(#"{"instrumental":true}"#.utf8)
check(LyricsDocument.decode(instrumental)?.phase == "instrumental", "instrumental response")
check(LyricsDocument.decode(Data(#"{"plainLyrics":"Original test sentence"}"#.utf8))?.phase == "unsynced", "unsynced fallback")
check(LyricsDocument.decode(Data("broken".utf8)) == nil, "bad JSON")
print("13 lyrics parser/timeline checks passed")
let sample = Data(#"{"trackName":"Example","artistName":"Test","duration":20,"syncedLyrics":"[00:00.00]Opening\n[00:10.00]Closing"}"#.utf8)
check(LyricsDocument.decode(sample)?.lines.count == 2, "API response decoding")
check(LyricsDocument.decode(sample)?.active(at: 10) == 1, "decoded timeline seeking")
print("2 API decoding checks passed")
let xml = #"<tt xmlns="http://www.w3.org/ns/ttml" xmlns:ttm="http://www.w3.org/ns/ttml#metadata"><body><div><p begin="0:01.000" end="00:00:05.000"><span begin="1.0" end="2.0">Hel</span><span begin="2.0" end="3.0">lo</span> <span begin="3.0" end="4.0">🌍</span><span ttm:role="x-bg"><span begin="3" end="4">ignored backing</span></span></p></div></body></tt>"#
let rich = TTMLLyrics.parse(xml)!
check(rich.phase == "word-synced", "rich timing classification")
check(rich.lines[0].text == "Hello 🌍", "preserves inter-span whitespace and skips backing vocals")
check(rich.lines[0].segments.count == 3, "timed syllable count")
check(rich.lines[0].highlight(at: 1.5) == NSRange(location:0,length:3), "first syllable range")
check(rich.lines[0].highlight(at: 2) == NSRange(location:3,length:2), "boundary uses next syllable")
check(rich.lines[0].highlight(at: 3.5) == NSRange(location:6,length:2), "emoji UTF16 range")
check(rich.lines[0].highlight(at: 4) == nil, "highlight stops at segment end")
check(rich.lines[0].highlight(at: 1.5) == NSRange(location:0,length:3), "backward seek is deterministic")
check(TTMLLyrics.time("1:16.656") == 76.656, "minute clock format")
check(TTMLLyrics.time("00:01:30.500") == 90.5, "hour clock format")
check(TTMLLyrics.time("NaN") == nil && TTMLLyrics.time("-1") == nil, "invalid timings rejected")
check(TTMLLyrics.parse("<!DOCTYPE x [<!ENTITY bad SYSTEM 'file:///etc/passwd'>]><tt/>") == nil, "external entities rejected")
check(TTMLLyrics.parse("<tt><body><p begin='1' end='2'>broken") == nil, "malformed XML rejected")
let wrapper = "<tt><body><p begin='1' end='4'><span begin='1' end='4'><span begin='1' end='2'>One</span><span begin='2' end='4'>Two</span></span></p></body></tt>"
check(TTMLLyrics.parse(wrapper)?.lines.first?.segments.count == 2, "nested wrappers do not double count")
let lineOnly = TTMLLyrics.parse("<tt><body><p begin='1' end='4'>Original example</p></body></tt>")!
check(lineOnly.phase == "synced" && lineOnly.lines[0].segments.isEmpty, "never fabricates word timings")
print("15 rich timing and safety checks passed")
let sung = rich.lines[0]
check(sung.sweep(at: 0)?.fraction == 0, "no fill before vocal starts")
check(sung.sweep(at: 1.25)?.fraction == 0.25, "quarter syllable sweep")
check(sung.sweep(at: 1.5)?.fraction == 0.5, "half syllable sweep")
check(sung.sweep(at: 1.75)?.fraction == 0.75, "three-quarter sweep")
check(sung.sweep(at: 2)?.range.location == 3 && sung.sweep(at: 2)?.fraction == 0, "next segment starts at prior fill boundary")
check(sung.sweep(at: 20)?.fraction == 1, "completed line keeps its fill")
check(sung.sweep(at: 1.5) == sung.sweep(at: 1.5), "pause holds fill")
check(sung.sweep(at: 1.25)?.fraction == 0.25, "backward seek rewinds fill")
check(lineOnly.lines[0].sweep(at: 2) == nil, "no artificial sweep without segment timestamps")
check(sung.sweep(at: .nan) == nil, "invalid sweep clock rejected")
print("10 smooth karaoke sweep checks passed")

// Response headers are untrusted and must not overflow DispatchTime deadlines.
check(LyricsRetryDelay.seconds("1e308", fallback: 2) == 300, "clamps huge numeric retry delay")
check(LyricsRetryDelay.seconds("Infinity", fallback: 2) == 2, "rejects infinite retry delay")
check(LyricsRetryDelay.seconds("NaN", fallback: 2) == 2, "rejects NaN retry delay")
check(LyricsRetryDelay.seconds("-999", fallback: 2) == 1, "floors negative retry delay")
check(LyricsRetryDelay.seconds(" 12 ", fallback: 2) == 12, "accepts bounded numeric retry delay")
check(LyricsRetryDelay.seconds("invalid", fallback: .infinity) == 60, "safe invalid fallback")
check(LyricsRetryDelay.seconds("Wed, 01 Jan 2098 00:00:00 GMT", fallback: 2, now: Date(timeIntervalSince1970: 0)) == 300, "clamps distant retry date")
check(LyricsRetryDelay.seconds(nil, fallback: 9999) == 300, "clamps fallback")
check(!ArtworkImage.dimensionsAllowed(width: 8193, height: 1), "rejects huge image edge")
check(!ArtworkImage.dimensionsAllowed(width: 5000, height: 5000), "rejects image pixel bomb")
check(!ArtworkImage.dimensionsAllowed(width: .nan, height: 128), "rejects invalid dimensions")
check(!ArtworkImage.dimensionsAllowed(width: 0, height: 128), "rejects zero dimensions")
check(ArtworkImage.dimensionsAllowed(width: 1024, height: 1024), "allows ordinary artwork")
check(ArtworkImage.decode(Data("not an image".utf8)) == nil, "rejects malformed image")
check(ArtworkImage.decode(Data(repeating: 0, count: 2_000_001)) == nil, "rejects oversized artwork")
let bitmap = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 512, pixelsHigh: 256, bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0)!
let png = bitmap.representation(using: .png, properties: [:])!
let thumbnail = ArtworkImage.decode(png)!
check(thumbnail.size.width <= 128 && thumbnail.size.height <= 128, "decodes bounded real PNG thumbnail")
print("16 retry-header and artwork safety checks passed")
